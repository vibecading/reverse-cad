"""One table of every solved case against its reference values.

usage: python -I bench.py [--out BENCH.md]

Reads the result files already in cases/ (single-photo `result_*.json`, joint
`joint_*.json`) and the camera sweep (`variants_*.json`) where there is one.
A parameter the sweep found unstable, or whose bootstrap spread exceeds 5 % of
its value, is listed as "not determined" and kept out of the error counts:
quoting its value would be quoting noise.
"""
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from dag import names as expr_names  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

RUNS = [
    ('Farnsworth House', 'photo 9970', 'cases/farnsworth/result_9970.json', 'cases/farnsworth/variants_9970.json', 'HABS IL-1105'),
    ('Farnsworth House', 'photo 9995', 'cases/farnsworth/result_9995.json', 'cases/farnsworth/variants_9995.json', 'HABS IL-1105'),
    ('Farnsworth House', '9970 + 9995 together', 'cases/farnsworth/joint_9970_9995.json', None, 'HABS IL-1105'),
    ('S. R. Crown Hall', 'photo c1', 'cases/crownhall/result_c1.json', 'cases/crownhall/variants_c1.json', 'Wikipedia'),
    ('Robie House', 'photo w1', 'cases/robie/result_w1.json', 'cases/robie/variants_w1.json', 'HABS ILL-1005'),
    ('Robie House', 'photo w2', 'cases/robie/result_w2.json', 'cases/robie/variants_w2.json', 'HABS ILL-1005'),
    ('Robie House', 'w1 + w2 together', 'cases/robie/joint_w1_w2.json', None, 'HABS ILL-1005'),
    ('Gamble House', 'photo g5', 'cases/gamble/result_g5.json', None, 'Greene & Greene 1908 (HABS CA-1981)'),
    ('Gamble House', 'photo g4', 'cases/gamble/result_g4.json', None, 'Greene & Greene 1908 (HABS CA-1981)'),
    ('Gamble House', 'g5 + g4 together', 'cases/gamble/joint_g5_g4.json', None, 'Greene & Greene 1908 (HABS CA-1981)'),
]


def load(p):
    p = os.path.join(ROOT, p)
    return json.load(open(p, encoding='utf-8')) if os.path.exists(p) else None


def main():
    rows, stats = [], {}
    for building, run, rp, vp, ref in RUNS:
        r = load(rp)
        if not r:
            continue
        v = load(vp) if vp else None
        unstable = set(v['unstable']) if v else set()
        sd = r.get('param_sd', {})
        st = stats.setdefault(run if 'together' in run else 'single photo', [])
        for k, t in r.get('vs_truth', {}).items():
            used = expr_names(k)
            # undetermined: the camera sweep moves it, or the bootstrap spread is over 5 % of it
            und = bool(used & unstable) or any(n in sd and sd[n] > 0.05 * abs(r['params'][n]) for n in used)
            e = t['err_pct']
            rows.append((building, run, k, t['solved'], sd.get(k), t['truth'], e, und, ref))
            if not und and abs(t['truth']) >= 1.0:  # a percentage of a small offset says little
                st.append(abs(e))
    lines = ['# Benchmark: photo solves against reference values', '',
             'Generated by `tools/bench.py` from the result files in `cases/`. Error is (solved - reference) / reference.',
             '"not determined" = the camera sweep (`tools/variants.py`) moves the value by more than 5 %; such rows are not counted.',
             '', '| building | solve | quantity | solved, m | +- | reference, m | error | source |', '|---|---|---|---|---|---|---|---|']
    for b, run, k, val, s, t, e, und, ref in rows:
        err = 'not determined' if und else '%+.1f %%' % e
        lines.append('| %s | %s | `%s` | %.3f | %s | %.3f | %s | %s |' % (b, run, k, val, '%.3f' % s if s else '', t, err, ref))
    lines += ['', '## Counts', '', '| solves | quantities | within 1 % | within 3 % | within 5 % | worst |', '|---|---|---|---|---|---|']
    for name, errs in stats.items():
        if not errs:
            continue
        n = len(errs)
        lines.append('| %s | %d | %d | %d | %d | %.1f %% |' % (name, n, sum(e <= 1 for e in errs), sum(e <= 3 for e in errs),
                                                        sum(e <= 5 for e in errs), max(errs)))
    text = '\n'.join(lines) + '\n'
    print(text)
    if '--out' in sys.argv:
        open(os.path.join(ROOT, sys.argv[sys.argv.index('--out') + 1]), 'w', encoding='utf-8').write(text)


if __name__ == '__main__':
    main()
