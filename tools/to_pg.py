"""Write a solve as a paramgraph model file (the text format of vibecading-model).

usage: python -I to_pg.py spec.json result.json [--name NAME] [--boxes boxes.pg] [--variants v.json] [--out model.pg]

Parameters come from the result with their grade (dag.py rules: free ones are
D, fixed ones P or A by their note), the bootstrap spread in the note, and a
"not determined" flag from the camera sweep. The spec's truth values become
checks with a tolerance of 3 % (at least 5 cm). Geometry is case-specific:
pass the box statements of the case with --boxes. A joint result
(`solve_multi.py`) works the same way; give any one of its specs.
"""
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from dag import grade  # noqa: E402


def q(s):
    return '"' + str(s).replace('"', '\\"') + '"'


def main():
    a = sys.argv[1:]
    opt = lambda k: a[a.index(k) + 1] if k in a else None
    spec = json.load(open(a[0], encoding='utf-8'))
    res = json.load(open(a[1], encoding='utf-8'))
    var = json.load(open(opt('--variants'), encoding='utf-8')) if opt('--variants') else None
    unstable = set(var['unstable']) if var else set()
    P = res['params']
    sd = res.get('param_sd', {})
    lines = ['model %s' % q(opt('--name') or os.path.basename(spec['image'])),
             '# frame: %s' % spec.get('frame', ''),
             '# generated by tools/to_pg.py from %s and %s' % (os.path.basename(a[0]), os.path.basename(a[1])),
             '# source photo: %s' % spec.get('source', spec['image']), '']
    width = max(len(k) for k in P)
    for k, p in spec['params'].items():
        g = grade(k, p)
        note = p.get('note', '')
        if k in sd:
            note += '%s+-%.3f m' % ('; ' if note else '', sd[k])
        if k in unstable:
            note += '; not determined: the camera sweep moves it by more than 5 %'
        lines.append('param %-*s = %.4f %s %s' % (width, k, P[k], g, q(note)))
    if opt('--boxes'):
        lines += ['', open(opt('--boxes'), encoding='utf-8').read().strip()]
    if spec.get('truth'):
        lines.append('')
        src = spec.get('truth_source', 'reference')
        for k, t in spec['truth'].items():
            tol = max(0.03 * abs(t), 0.05)
            lines.append('check %s = %s tol %.3f %s' % (k, t, tol, q(src.split('.')[0])))
    text = '\n'.join(lines) + '\n'
    if opt('--out'):
        open(opt('--out'), 'w', encoding='utf-8').write(text)
    else:
        sys.stdout.write(text)


if __name__ == '__main__':
    main()
